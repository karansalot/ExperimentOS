"""Markdown reports generated from the cached artifacts, so documented numbers cannot drift from computed ones."""
from __future__ import annotations

from pathlib import Path

from . import artifacts, config
from .brief import pct, pp, pval
from .simulator.decision import Scenario, simulate

DOCS = config.ROOT / "docs"


def _table(headers: list[str], rows: list[list]) -> list[str]:
    return ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers), *["| " + " | ".join(str(c) for c in r) + " |" for r in rows], ""]


def _stamp(meta: dict) -> str:
    scope = "DEVELOPMENT SAMPLE (not full-dataset results)" if meta["is_sample"] else "full dataset"
    return (f"> Generated by `python -m experimentos.pipeline reports` from `artifacts/{meta['scope']}/`. Do not edit by hand.  \n"
            f"> Scope: **{scope}**, {meta['n_rows']:,} rows · {meta['dataset']} · raw sha256 `{meta['raw_sha256'][:16]}…` · "
            f"seed {meta['seed']} · artifacts built {meta['generated_at']}")


def data_quality_report(scope: str) -> str:
    a = artifacts.read(scope, "data_quality")
    d, meta = a["data"], a["meta"]
    man = artifacts.read(scope, "dataset")["data"]["manifest"]
    L = ["# Data quality report", "", _stamp(meta), "", "## Source", "",
         f"- **Dataset:** {config.DATASET['name']} {config.DATASET['version']} ({config.DATASET['publisher']})",
         f"- **File:** `{config.DATASET['raw_filename']}`, {config.DATASET['raw_bytes']:,} bytes, pinned to Hugging Face revision `{config.DATASET['hf_revision'][:12]}`",
         f"- **SHA-256:** `{config.DATASET['raw_sha256']}` (verified before every ingest)",
         f"- **License:** {config.DATASET['license']} (non-commercial, share-alike, attribution)",
         f"- **Citation:** {config.DATASET['citation']}", "",
         "## Dataset card vs verified values", "",
         "The dataset card contradicts itself (row count and feature count), so nothing below is quoted from it without checking.", ""]
    L += _table(["Property", "Dataset card", f"Verified ({meta['scope_label']})"], [[c["field"], c["card_statement"], c["verified"]] for c in d["dataset_card_comparison"]])
    L += ["## Validation rules", "", f"All error-severity checks passed: **{d['all_error_checks_passed']}**", ""]
    L += _table(["Check", "Severity", "Violating rows", "Result"], [[f"`{c['check_name']}`", c["severity"], f"{c['violating_rows']:,}", "pass" if c["passed"] else "**FAIL**"] for c in d["checks"]])
    L += ["## Findings", ""]
    for f in d["findings"]:
        L += [f"- **{f['title']}** ({'caution' if f['severity'] == 'warn' else 'note'}). {f['detail']}"]
    L += ["", "## Schema after ingest", ""]
    L += _table(["Column", "Type", "Role"], [[f"`{c['column']}`", c["type"], c["role"]] for c in d["columns"][12:]] + [["`f0` … `f11`", "DOUBLE", d["columns"][0]["role"]]])
    L += ["## Feature profile", "", "Every feature has one dominant (modal) value. Segments therefore use the modal value plus terciles of the remaining values rather than NTILE, which would split ties arbitrarily.", ""]
    L += _table(["Feature", "Distinct values", "Min", "Max", "Mean", "Share at modal value"],
                [[f["feature"], f"{f['distinct_values']:,}", f["min_value"], f["max_value"], f["mean_value"], pct(f["share_at_modal_value"], 1)] for f in d["feature_profile"]])
    L += ["## Exact duplicate rows", ""]
    L += _table(["Copies per distinct row", "Distinct rows", "Total rows", "% of all rows"], [[x["copies_per_distinct_row"], f"{x['distinct_rows']:,}", f"{x['total_rows']:,}", x["pct_of_all_rows"]] for x in d["duplicates"]])
    L += ["## Row order is structured, not random", "",
          "Twenty equal-size blocks by file position. Several blocks contain a single arm, and the visit rate changes several-fold between blocks, so `LIMIT n`, head/tail splits or sequential sampling would be biased. Splits and the development sample use a salted hash of row position instead.", ""]
    L += _table(["Block", "First row", "Treatment share", "Visit rate", "Mean f0"], [[b["block"], f"{b['first_row_id']:,}", b["treatment_share"], b["visit_rate"], b["mean_f0"]] for b in d["file_order"]])
    L += ["## Train / validation / test split", ""]
    L += _table(["Split", "Rows", "Share", "Duplicate row ids", "Treatment share", "Visit rate", "Conversion rate"],
                [[s["split"], f"{s['n_users']:,}", s["share_of_rows"], s["duplicate_row_ids"], s["treatment_share"], s["visit_rate"], s["conversion_rate"]] for s in d["split_integrity"]])
    if not meta["is_sample"]:
        L += ["## Development sample representativeness", "", f"The development sample is `{man['dev_sample_rule']}`. z compares it with the remaining rows.", ""]
        L += _table(["Metric", "Dev sample", "Rest of data", "z"], [[s["metric"], s["dev_sample_rate"], s["rest_rate"], s["z_statistic"]] for s in d["dev_sample_representativeness"]])
    return "\n".join(L)


def _ci(m: dict, scale: float = 1000, d: int = 2) -> str:
    if "low" not in m:
        return f"{m['value'] * scale:.{d}f}"
    return f"{m['value'] * scale:.{d}f} [{m['low'] * scale:.{d}f}, {m['high'] * scale:.{d}f}]"


def model_evaluation_report(scope: str) -> str:
    a = artifacts.read(scope, "models")
    d, meta = a["data"], a["meta"]
    diag = artifacts.read(scope, "diagnostics")["data"]
    exp = artifacts.read(scope, "experiment")["data"]
    run = d["run"]
    L = ["# Model evaluation report", "", _stamp(meta), "",
         "## Protocol", "",
         "- **Splits:** 60% train / 20% validation / 20% test from a salted hash of row position. Models are fitted on train, the champion is chosen on validation, and every number in this report is from test.",
         "- **Strategies:** random targeting; response-propensity baseline; two-model (logistic); T-learner (gradient boosting); S-learner (gradient boosting).",
         "- **Uncertainty:** paired Poisson bootstrap over test users "
         f"({run['n_boot']} replicates, the same resamples for every strategy), 95% percentile intervals.",
         "- **Two evaluation bases:** *unadjusted* (treated minus control rate inside the targeted group) and *adjusted* (mean cross-fitted doubly-robust score inside the targeted group). They are reported side by side because arms are slightly imbalanced on features in this file.",
         f"- **Reproducibility:** seed {run['seed']}; scikit-learn {run['tooling']['scikit_learn']}; training wall time {run['seconds']:.0f}s.", "",
         "Leakage controls:", "", *[f"- {c}" for c in run["leakage_controls"]], "",
         "## Why two bases: the arms are not perfectly comparable", ""]
    c2 = diag["adjusted"]["classifier_two_sample_test"]
    L += [f"A cross-fitted classifier predicts assignment from features with AUC **{c2['auc']:.3f}** (0.500 would mean indistinguishable; p {pval(c2['p_value'])}). "
          f"The largest standardised mean difference is {diag['verdict']['max_abs_smd']:.3f} ({diag['verdict']['worst_feature']}). The effect of that on the average treatment effect:", ""]
    rows = []
    for o in config.OUTCOMES:
        for e in diag["adjusted"]["outcomes"][o]["estimators"]:
            rows.append([o, e["method"], pp(e["estimate"]), f"{pp(e['ci_low'])} to {pp(e['ci_high'])}", "–" if not e["relative_to_unadjusted"] else f"{e['relative_to_unadjusted']:+.0%}"])
    L += _table(["Outcome", "Estimator", "Effect", "95% CI", "vs unadjusted"], rows)
    for o in config.OUTCOMES:
        mo = d["outcomes"][o]
        r = mo["rows"]
        champ = next(m for m in mo["models"] if m["is_champion"])
        L += [f"## Outcome: {o}", "",
              f"Train {r['train']:,} rows ({r['train_treatment']:,} treatment / {r['train_control']:,} control, {r['train_positives']:,} positives); "
              f"test {r['test']:,} rows ({r['test_positives']:,} positives). Base rate in control: {pct(exp['outcomes'][o]['rate_control'], 3)}.", "",
              f"**Champion (selected on validation): {champ['name']}.** {mo['selection']['rule']}", "",
              f"Units: incremental {o}s per 1,000 users. *Gain over random* is the area between the strategy's cumulative uplift curve and the random-targeting line (average advantage over all targeting depths).", ""]
        rows = []
        for m in mo["models"]:
            t = m["test_metrics"]
            vs = t["gain_over_random_adjusted"].get("vs_reference")
            rows.append([
                ("**" + m["name"] + "**") if m["is_champion"] else m["name"],
                _ci(t["gain_over_random_adjusted"]), _ci(t["gain_over_random_unadjusted"]), _ci(t["qini_coefficient"]),
                _ci(t["uplift_at_10_adjusted"], 100, 2) + " pp",
                "–" if not vs or m["id"] == "random" else f"{vs['difference'] * 1000:+.2f} [{vs['low'] * 1000:.2f}, {vs['high'] * 1000:.2f}], P(better) {vs['prob_better']:.0%}",
                f"{m['validation_metrics']['gain_over_random_adjusted'] * 1000:.2f}", f"`{m['version']}`",
            ])
        L += _table(["Strategy", "Gain over random (adjusted)", "Gain over random (unadjusted)", "Qini coefficient", "Effect in top 10% (adjusted)", "Δ vs response baseline (adjusted)", "Validation gain", "Version"], rows)
        L += [f"### Calibration of predicted uplift: {champ['name']}", "", "Deciles of predicted uplift on the test split (1 = highest predictions).", ""]
        L += _table(["Decile", "Users", "Treated share", "Mean predicted", "Observed (unadjusted) ± 1.96 SE", "Observed (adjusted) ± 1.96 SE"],
                    [[c["group"], f"{c['n_users']:,}", pct(c["treatment_share"], 1), pp(c["mean_predicted_uplift"]),
                      f"{pp(c['observed_uplift'])} ± {1.96 * c['observed_std_error'] * 100:.3f}",
                      f"{pp(c['observed_uplift_adjusted'])} ± {1.96 * c['observed_adjusted_std_error'] * 100:.3f}"] for c in champ["calibration"]])
        L += ["### Outcome-model diagnostics (test split, scored in the arm each model describes)", ""]
        rows = []
        for m in mo["models"]:
            for arm, g in (m.get("outcome_models") or {}).items():
                rows.append([m["name"], arm, f"{g['n']:,}", f"{g['positives']:,}", f"{g['auc']:.3f}", f"{g['log_loss']:.4f}", f"{g['brier']:.5f}"])
        L += _table(["Strategy", "Arm modelled", "Test users", "Positives", "AUC", "Log loss", "Brier"], rows)
    if artifacts.exists(scope, "explain"):
        ex = artifacts.read(scope, "explain")["data"]
        smp = ex["importance_sample"]
        L += ["## Explainability (champion models, test split)", "",
              f"Permutation importance uses a seeded sample of {smp['rows']:,} of {smp['of_test_rows']:,} test users ({smp['repeats']} shuffles per feature); "
              "segment agreement and the persuadables profile use every test user.", ""]
        for o, e in ex["outcomes"].items():
            L += [f"### {o}: {e['model_name']}", "",
                  f"Predicted vs observed (doubly-robust) uplift across {len(e['segment_agreement'])} feature segments: correlation "
                  f"**{e['agreement_correlation']:.3f}**, size-weighted mean absolute gap {e['agreement_weighted_mae'] * 100:.3f} pp.", ""]
            L += _table(["Feature", "Lost gain per 1,000 users", "Share of gain", "Range over shuffles"],
                        [[r["feature"], f"{r['drop'] * 1000:.3f}", f"{(r['share_of_gain'] or 0):.1%}", f"{r['drop_min'] * 1000:.3f} to {r['drop_max'] * 1000:.3f}"] for r in e["importance"][:6]])
            L += _table(["Feature", "Std. difference (top 10% vs rest)", "Off modal: top 10%", "Off modal: rest"],
                        [[r["feature"], f"{r['smd']:+.2f}", pct(r["share_off_modal_top"], 0), pct(r["share_off_modal_rest"], 0)] for r in e["persuadables"][:5]])
    L += ["## Reading the results", "",
          "- Outcome models discriminate well (AUC well above 0.9), yet uplift models improve on the response baseline only modestly or not at all. In this dataset the users most likely to respond are also the users who respond most to treatment, so a response model is a strong uplift ranker. That is an empirical property of this data, not a general rule.",
          "- A model is declared better than the response baseline only when the paired bootstrap interval for the difference excludes zero.",
          "- Conversion is roughly sixteen times rarer than visit, so its uplift rankings are noisier; flexible learners can lose to simpler ones there.",
          "- No causal forest was trained: the two-model, T- and S-learner comparison answers the targeting question here, and an honest forest on millions of rows adds cost without a decision that depends on it. EconML/CausalML are therefore not dependencies.", ""]
    return "\n".join(L)


def results_snapshot(scope: str) -> str:
    exp = artifacts.read(scope, "experiment")
    e, meta = exp["data"], exp["meta"]
    diag = artifacts.read(scope, "diagnostics")["data"]
    L = ["# Results snapshot", "", _stamp(meta), "", "## Treatment effects (intent-to-treat)", ""]
    rows = []
    for o in config.OUTCOMES:
        x = e["outcomes"][o]
        dr = next(m for m in diag["adjusted"]["outcomes"][o]["estimators"] if m["method"].startswith("AIPW"))
        rows.append([o, pct(x["rate_control"], 3), pct(x["rate_treatment"], 3), f"{pp(x['absolute_effect'])} [{pp(x['ci_low'])}, {pp(x['ci_high'])}]",
                     f"{x['relative_effect']:+.1%}", f"{pp(dr['estimate'])} [{pp(dr['ci_low'])}, {pp(dr['ci_high'])}]", f"{x['z_statistic']:.1f}"])
    L += _table(["Outcome", "Control", "Treatment", "Unadjusted effect [95% CI]", "Relative", "Doubly-robust effect [95% CI]", "z"], rows)
    s = e["srm"]
    c2 = diag["adjusted"]["classifier_two_sample_test"]
    L += ["## Validity", "",
          f"- Sample ratio: {pct(s['observed_treatment_share'], 4)} treated vs {pct(s['expected_treatment_share'], 0)} design, chi-square p = {pval(s['p_value'])}.",
          f"- Balance: {diag['verdict']['headline']} Max |SMD| {diag['verdict']['max_abs_smd']:.3f}; assignment-predictability AUC {c2['auc']:.3f}.",
          f"- Exposure: {pct(e['exposure']['exposure_rate_treatment'], 2)} of treated users exposed; none in control.", "",
          "## Default scenario (illustrative assumptions, not data)", ""]
    for o in config.OUTCOMES:
        sc = Scenario(outcome=o)
        r = simulate(scope, sc)
        rec = r["recommendation"]
        rows = {x["id"]: x for x in r["strategies"]}
        L += [f"- **{o}**: cost {sc.cost_per_user} per user, value {sc.value_per_outcome} per incremental {o}, population {sc.population:,}, "
              f"{r['scenario']['risk_criterion']}. Recommended: {rec['name']} at {rec['targeting_pct']:.0f}% coverage, scenario profit "
              f"{rec['profit']:,.0f} (95% interval {rec.get('profit_low') or 0:,.0f} to {rec.get('profit_high') or 0:,.0f}). "
              f"Treat everyone: {rows['all']['profit']:,.0f}."]
    L += [""]
    return "\n".join(L)


def sql_catalog(scope: str) -> str:
    a = artifacts.read(scope, "sql")
    L = ["# SQL catalog", "", _stamp(a["meta"]), "",
         "DuckDB over Parquet. Views live in `backend/experimentos/sql/views/`, queries in `backend/experimentos/sql/queries/`. "
         "Every query runs on every pipeline run and in the test suite.", "",
         "## Views", "",
         "- `experiment`: the Parquet file plus the derived `split` column.",
         "- `v_arm_summary`: counts and rates per arm (the sufficient statistics for every test).",
         "- `v_feature_long`: UNPIVOT of the 12 features to one row per (user, feature).",
         "- `feature_value_stats`: materialised outcome counts per (feature, distinct value, arm).",
         "- `v_feature_segments` / `v_segment_arm_stats`: modal-value + weighted-tercile segments built with window functions.",
         "- `predictions`: held-out model scores and doubly-robust scores (after training).", "",
         "## Queries", ""]
    L += _table(["#", "Query", "Technique", "Question", "Rows", "Seconds"],
                [[q["id"][:2], f"[{q['title']}](../backend/experimentos/sql/queries/{q['id']}.sql)", q["technique"], q["question"],
                  q.get("row_count", "–"), q.get("seconds", "–")] for q in a["data"]["queries"]])
    return "\n".join(L)


def insights_report(scope: str) -> str:
    from . import insights

    r = insights.build(scope)
    L = ["# Key insights", "", _stamp(r["meta"]), "",
         "Generated by the same engine that drives the dashboard's Insights page. Each finding links to the page that shows its evidence.", ""]
    for k, i in enumerate(r["insights"], 1):
        L += [f"## {k}. {i['title']}", "", f"**{i['value']}** · *{i['kicker']}* · evidence: `{i['href']}`", "", i["detail"], ""]
    return "\n".join(L)


def write_all(scope: str = "full") -> list[Path]:
    if not artifacts.exists(scope, "models"):
        raise FileNotFoundError(f"No artifacts for scope {scope!r}; run the pipeline first.")
    DOCS.mkdir(exist_ok=True)
    out = []
    for name, fn in [("DATA_QUALITY_REPORT.md", data_quality_report), ("MODEL_EVALUATION_REPORT.md", model_evaluation_report), ("RESULTS.md", results_snapshot), ("SQL_CATALOG.md", sql_catalog), ("INSIGHTS.md", insights_report)]:
        p = DOCS / name
        p.write_text(fn(scope) + "\n")
        out.append(p)
    return out
